"""Runs a replace and an insert on every fixture and records which formatting
properties were verified as preserved and which were not.

Output: tests/reports/preservation_report.md (regenerated on every run).
"""
from pathlib import Path

from careercopilot.docx_io import read_docx
from careercopilot.edit_docx import apply_docx_edit, verify_docx_edit
from careercopilot.edit_pdf import apply_pdf_edit, verify_pdf_edit
from careercopilot.pdf_io import read_pdf

from conftest import AS_OF, fixture_bytes

OUT = Path(__file__).parent / "reports" / "preservation_report.md"
CASES = [
    ("classic.docx", "Single column, Calibri 11, List Bullet numbering, right tab stops, header with hyperlink, footer, skills table, page break"),
    ("two_column_table.docx", "Two-column layout table, Georgia 10.5, manual en-dash bullets in coloured runs, bold labels"),
    ("section_columns.docx", "Section with 2 text columns (w:cols), numbered list, Times New Roman 12, underlined headings"),
    ("single_column.pdf", "Single column, standard Helvetica fonts, rule lines, link annotation"),
    ("two_column.pdf", "Two columns, embedded TrueType subsets (Arial), coloured sidebar, coloured bullets, 2 pages, page numbers"),
    ("tight_page.pdf", "Page filled to the bottom margin, Times fonts (forces overflow on insert)"),
    ("scanned.pdf", "Image-only scan (OCR)"),
]
REPLACE = "Containerized three legacy services with Docker and migrated them to the cloud."
INSERT = ("Deployed containerized services with Docker to AWS, cutting release time by half across all product "
          "teams and standardizing the build process for every service.")


def _run(name):
    data = fixture_bytes(name)
    rows = []
    for mode, text in (("replace", REPLACE), ("insert_after", INSERT)):
        if name.endswith(".docx"):
            m = read_docx(data, AS_OF)
            b = next(x for x in m.blocks if x.kind == "bullet" and "Containerized" in x.text)
            op = {"mode": mode, "block_id": b.id, "text": text}
            out, info = apply_docx_edit(data, op)
            rep = verify_docx_edit(data, out, op, info)
        else:
            m, lay = read_pdf(data, AS_OF)
            b = next(x for x in m.blocks if x.kind == "bullet" and "Containerized" in x.text)
            op = {"mode": mode, "block_id": b.id, "text": text}
            out, geom = apply_pdf_edit(data, lay, op)
            rep = verify_pdf_edit(data, out, lay, op, geom)
        rows.append((mode, rep))
    return rows


def test_write_preservation_report():
    lines = ["# Formatting preservation report", "",
             "Generated by `tests/test_preservation_report.py`. Each fixture receives one in-place replacement "
             "and one inserted bullet; every property below was checked by re-opening the exported file.", ""]
    summary = []
    for name, desc in CASES:
        lines += [f"## {name}", f"_{desc}_", ""]
        for mode, rep in _run(name):
            not_ok = [p for p in rep["properties"] if p["status"] != "preserved"]
            summary.append((name, mode, rep["exact"], ", ".join(f"{p['property']} ({p['status']})" for p in not_ok) or "–"))
            lines += [f"### {mode} — {'all verified properties preserved' if rep['exact'] else 'see limitations'}",
                      f"Method: {rep['method']}", "", "| Status | Property | Detail |", "|---|---|---|"]
            lines += [f"| {p['status']} | {p['property']} | {p['detail'].replace('|', '/')} |" for p in rep["properties"]]
            lines.append("")
            # Critical integrity properties must always hold, even when layout is approximated.
            critical = {"Unaffected text: fonts, sizes, colours, positions", "No hidden or duplicated text (pdfminer)",
                        "Edited text written", "Edited text written exactly", "Valid PDF", "Valid, editable DOCX package",
                        "Unrelated paragraphs (headings, dates, contact info, section order)"}
            assert all(p["status"] == "preserved" for p in rep["properties"] if p["property"] in critical), (name, mode, not_ok)
    lines[4:4] = ["| Fixture | Edit | Exact | Not preserved / approximated |", "|---|---|---|---|"] + \
        [f"| {n} | {m} | {'yes' if e else 'no'} | {d} |" for n, m, e, d in summary] + [""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
